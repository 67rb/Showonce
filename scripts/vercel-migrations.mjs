import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const drizzle = join(root, 'services/learning/hashir/public-site/drizzle');
const outDir = join(root, 'server');
mkdirSync(outDir, { recursive: true });

// Split SQL into top-level statements. Tracks single/double-quoted strings and
// paren depth so a ';' inside a string or CREATE TABLE body is not a boundary.
function splitStatements(sql) {
  const statements = [];
  let current = '';
  let quote = null;
  let depth = 0;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    const next = sql[i + 1];
    if (quote) {
      current += ch;
      if (ch === '\\' && next) { current += next; i++; }
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"') { quote = ch; current += ch; continue; }
    if (ch === '(') { depth++; current += ch; continue; }
    if (ch === ')') { depth--; current += ch; continue; }
    if (ch === ';' && depth === 0) {
      const stmt = stripComments(current).trim();
      if (stmt) statements.push(stmt);
      current = '';
      continue;
    }
    current += ch;
  }
  const last = stripComments(current).trim();
  if (last) statements.push(last);
  return statements;
}

// Remove full-line and inline SQL comments (lines starting with --, and trailing --).
function stripComments(sql) {
  return sql
    .split('\n')
    .map((line) => {
      const t = line.trim();
      if (t.startsWith('--')) return '';
      return line;
    })
    .join('\n');
}

const files = readdirSync(drizzle).filter((f) => f.endsWith('.sql')).sort();
const migrations = [];
for (const f of files) {
  const raw = readFileSync(join(drizzle, f), 'utf8');
  const statements = splitStatements(raw);
  migrations.push({ name: f.replace('.sql', ''), statements });
}

const out = `// Generated by scripts/vercel-migrations.mjs — do not edit manually.
export const MIGRATIONS = ${JSON.stringify(migrations, null, 1)};\n`;
writeFileSync(join(outDir, 'vercel-migrations.mjs'), out);
console.log(`Wrote server/vercel-migrations.mjs: ${migrations.length} migrations, ${migrations.reduce((n, m) => n + m.statements.length, 0)} statements`);